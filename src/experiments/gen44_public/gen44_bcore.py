def frame_of_ext(e, vars_, nv):
    out = []
    try:
        for j in range(F.K_GRID):
            env = F.grid_env(vars_, nv, j)
            v = numeric_of_sq(e.subs(env))
            v = sp.nsimplify(v)
            out.append(float(sp.N(v, 14)))
        return out
    except Exception:                                                   # noqa: BLE001
        return None


def assert_frames(frames, claim_val=None):
    """Mechanical assertions: first frame non-degenerate · chain is not frame-constant ·
    frames differ from the claimed answer."""
    bad = []
    if not frames:
        return ["frames_empty"]
    if len(frames) >= 2 and F.frames_all_equal(frames):
        bad.append("frame_constant_chain")
    if claim_val is not None:
        c = [float(claim_val)] * F.K_GRID
        if frames[0] == c:
            bad.append("frame_equals_claim")
    return bad


