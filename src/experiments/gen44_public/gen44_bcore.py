def wilson(k, n, z=1.96):
    if n == 0:
        return [0.0, 0.0]
    p = k / n
    dd = 1 + z * z / n
    c = (p + z * z / (2 * n)) / dd
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / dd
    return [round(max(0.0, c - h), 4), round(min(1.0, c + h), 4)]


