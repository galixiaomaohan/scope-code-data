# ================================================================ §1 sqrt atomization + exact values
_SQH = re.compile(r"(?:Real\s*\.\s*sqrt|√)\s*")


def _arg_span(t, i):
    n = len(t)
    while i < n and t[i] == " ":
        i += 1
    if i >= n:
        return None
    if t[i] == "(":
        d, j = 0, i
        while j < n:
            c = t[j]
            if c in "([{":
                d += 1
            elif c in ")]}":
                d -= 1
                if d == 0:
                    return (i, j + 1, t[i + 1:j])
            j += 1
        return None
    m = re.match(r"[A-Za-z_][A-Za-z0-9_'.]*|\d+(?:\s*/\s*\d+)?", t[i:])
    if not m:
        return None
    return (i, i + m.end(), m.group(0))


def _nthroot(i, n=2):
    try:
        r = sp.integer_nthroot(int(i), n)
        return r[0] if r[1] else None
    except Exception:                                                   # noqa: BLE001
        return None


def sqrt_value(e):
    """Closed-form exact value (Lean semantics: negative -> 0; perfect square -> rational;
    otherwise None = keep the atom)."""
    if e is None or e.free_symbols:
        return None
    try:
        v = sp.nsimplify(e)
    except Exception:                                                   # noqa: BLE001
        return None
    if not v.is_rational:
        return None
    if v < 0:
        return sp.Integer(0)
    p, q = int(v.p), int(v.q)
    rp, rq = _nthroot(p), _nthroot(q)
    if rp is None or rq is None or rq == 0:
        return None
    return sp.Rational(rp, rq)


def scrub_sqrt(txt):
    """Replace √arg / Real.sqrt arg with placeholder symbols s44_k; returns (new text,
    {placeholder: argument text})."""
    subs, out, k = {}, txt, 0
    for _ in range(96):
        m = _SQH.search(out)
        if not m:
            break
        s2 = _arg_span(out, m.end())
        if s2 is None:
            raise S.PErr("sqrtarg")
        a, b, arg = s2
        nm = "s44_%d" % k
        k += 1
        subs[nm] = arg
        out = out[:m.start()] + nm + out[b:]
    return out, subs


def parse_expr_ext(txt, vars_, types, nat_mode):
    """Extended expression parsing: reuse S.parse_arith's strict grammar plus sqrt atoms
    (exact when computable)."""
    t2, subs = scrub_sqrt(txt)
    vs = set(vars_) | set(subs)
    e, meta = S.parse_arith(t2, vs, types or {}, nat_mode)
    if subs:
        e = e.subs({sp.Symbol(n): _sq_atom(subs[n], vars_, types, nat_mode)
                    for n in subs})
        meta = dict(meta)
        meta["uses_sqrt"] = True
    return e, meta


def _sq_atom(arg, vars_, types, nat_mode):
    try:
        ae, _m = parse_expr_ext(arg, vars_, types, nat_mode)
    except Exception:                                                   # noqa: BLE001
        return SQ(sp.Symbol("s44_bad"))
    v = sqrt_value(ae)
    return v if v is not None else SQ(ae)


def has_sq(e):
    try:
        return any(getattr(a, "func", None) == SQ for a in e.atoms(sp.Function))
    except Exception:                                                   # noqa: BLE001
        return False


def sq_atoms(e):
    try:
        return sorted([a for a in e.atoms(sp.Function) if getattr(a, "func", None) == SQ],
                      key=str)
    except Exception:                                                   # noqa: BLE001
        return []


def numeric_of_sq(e):
    """Numerical substitute (for state frames; Lean semantics √x = 0 for x<0)."""
    try:
        reps = {a: sp.sqrt(sp.Max(a.args[0], 0)) for a in sq_atoms(e)}
        return e.subs(reps)
    except Exception:                                                   # noqa: BLE001
        return e


def uses_div_flag(e):
    try:
        for a in sp.preorder_traversal(e):
            if isinstance(a, sp.Pow) and getattr(a.exp, "is_number", False) and a.exp < 0:
                return True
            if isinstance(a, sp.Rational) and a.q != 1:
                return True
        return False
    except Exception:                                                   # noqa: BLE001
        return False


def meta_of(e):
    return {"uses_div": uses_div_flag(e), "uses_cast": False, "uses_mod": False,
            "uses_sub": False, "uses_abs": bool(e.atoms(sp.Abs)),
            "uses_fact": False, "uses_sympow": False, "nat_risk": False,
            "uses_sqrt": has_sq(e)}


# ================================================================ §2 extended statement parsing
_CONN_TOK = [("↔", 0), ("<->", 0), ("→", 1), ("->", 1), ("∨", 2), ("\\/", 2),
             ("∧", 3), ("/\\", 3)]


def top_conn(s):
    """**Loosest** connective at depth 0 -> (tok, idx) or (None, -1).
    Precedence ↔ < → < ∨ < ∧."""
    d, hits = 0, []
    i = 0
    while i < len(s):
        c = s[i]
        if c in "([{":
            d += 1
        elif c in ")]}":
            d -= 1
        elif d == 0:
            for tok, prec in _CONN_TOK:
                if s.startswith(tok, i):
                    hits.append((prec, i, tok))
                    i += len(tok) - 1
                    break
        i += 1
    if not hits:
        return None, -1
    hits.sort(key=lambda x: (x[0], x[1]))
    return hits[0][2], hits[0][1]


def _strip_parens(txt):
    t = txt.strip()
    if t.startswith("(") and t.endswith(")"):
        d = 0
        for i, c in enumerate(t):
            if c == "(":
                d += 1
            elif c == ")":
                d -= 1
                if d == 0 and i < len(t) - 1:
                    return t
        return t[1:-1].strip()
    return t


def parse_hyp_ext(ptxt, hname, vs, types, nat_mode):
    """One hypothesis (lenient; on failure returns None => recorded as extra_hyps, not a
    failure)."""
    h = parse_goal_ext_rel(ptxt, vs, types, nat_mode)
    if h is None:
        return None
    h["name"] = hname
    return h


def parse_goal_ext_rel(txt, vs, types, nat_mode):
    """Relational goal -> {rel,neg,lhs,rhs,txt,meta}; None on failure.
    ≥/> are normalized to ≤/< (swap sides; an equivalent transform that keeps the
    lin/subst/pos routes usable)."""
    t = txt.strip()
    neg = False
    while t.startswith("¬"):
        neg = not neg
        t = t[1:].strip()
    t = _strip_parens(t)
    rel, i = S.top_rel(t)
    if rel is None or i < 0:
        return None
    hl, hr = t[:i].strip(), t[i + 1:].strip()
    if not hl or not hr:
        return None
    try:
        e1, m1 = parse_expr_ext(hl, vs, types, nat_mode)
        e2, m2 = parse_expr_ext(hr, vs, types, nat_mode)
    except Exception:                                                   # noqa: BLE001
        return None
    if rel == "≥":
        rel, e1, e2, hl, hr = "≤", e2, e1, hr, hl
    elif rel == ">":
        rel, e1, e2, hl, hr = "<", e2, e1, hr, hl
    return {"rel": rel, "neg": neg, "lhs": e1, "rhs": e2, "txt": t,
            "lhs_txt": hl, "rhs_txt": hr,
            "meta": {k: bool(m1.get(k) or m2.get(k)) for k in m1}}


def _forall_split(s):
    """∀ binder block -> (parts, body, ok); parts=[("var",names,ty)|("anon",[],prop)]"""
    parts, i, n = [], 0, len(s)
    while True:
        while i < n and s[i] == " ":
            i += 1
        if i >= n:
            return None, None, False
        if s[i] == ",":
            return parts, s[i + 1:].strip(), True
        if s[i] == "(":
            d, j = 0, i
            while j < n:
                if s[j] in "([{":
                    d += 1
                elif s[j] in ")]}":
                    d -= 1
                    if d == 0:
                        break
                j += 1
            if j >= n:
                return None, None, False
            parts.append(_classify_binder(s[i + 1:j]))
            i = j + 1
            continue
        j = i
        while j < n and s[j] != "," and not (s[j] == "(" and j > i):
            j += 1
        seg = s[i:j].strip()
        i = j
        if seg:
            parts.append(_classify_binder(seg))


def _classify_binder(seg):
    seg = seg.strip()
    if not seg:
        return ("anon", [], "")
    d, ci = 0, -1
    for i, c in enumerate(seg):
        if c in "([{":
            d += 1
        elif c in ")]}":
            d -= 1
        elif c == ":" and d == 0:
            ci = i
            break
    if ci >= 0:
        names = [x for x in seg[:ci].split() if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_']*", x)]
        return ("var", names, seg[ci + 1:].strip())
    return ("anon", [], seg)


def build_tree(txt, types, hyps, nat_mode, depth=0):
    """Goal tree: forall / imp / iff / and / or / leaf / sqrt_red / fail.
    types = {variable name: type}; vs is derived from types."""
    if depth > 10:
        return {"kind": "fail", "reason": "depth"}
    vs = set(types)
    t = _strip_parens(txt)
    m = re.match(r"^(?:∀|forall)\s*", t)
    if m:
        parts, body, ok = _forall_split(t[m.end():])
        if not ok or body is None:
            return {"kind": "fail", "reason": "forall_syntax"}
        nv = dict(types)
        nh = list(hyps)
        intros, added = [], []
        for kind, names, ty in parts:
            if kind == "var":
                if ty not in S.NUMERIC_TYPES:
                    return {"kind": "fail", "reason": "forall_nonnum:%s" % ty[:12]}
                for n in names:
                    nv[n] = ty
                intros += names
            else:
                nm = "h44_%d" % len(intros)
                intros.append(nm)
                h = parse_goal_ext_rel(ty, set(nv), nv, nat_mode)
                if h is not None:
                    h["name"] = nm
                    nh.append(h)
                    added.append(nm)
        ch = build_tree(body, nv, nh, nat_mode, depth + 1)
        return {"kind": "forall", "intros": intros, "added": added,
                "types": nv, "hyps": nh, "children": [ch], "txt": t}
    tok, idx = top_conn(t)
    if tok == "↔" or tok == "<->":
        l, r = t[:idx].strip(), t[idx + len(tok):].strip()
        c1 = build_tree(r, types, hyps + _hyp_add(l, vs, types, nat_mode, "h44_l"),
                        nat_mode, depth + 1)
        c2 = build_tree(l, types, hyps + _hyp_add(r, vs, types, nat_mode, "h44_r"),
                        nat_mode, depth + 1)
        return {"kind": "iff", "children": [
            {"kind": "imp", "hypname": "h44_l", "children": [c1]},
            {"kind": "imp", "hypname": "h44_r", "children": [c2]}]}
    if tok == "→" or tok == "->":
        l, r = t[:idx].strip(), t[idx + len(tok):].strip()
        nh = hyps + _hyp_add(l, vs, types, nat_mode, "h44")
        ch = build_tree(r, types, nh, nat_mode, depth + 1)
        return {"kind": "imp", "hypname": "h44", "children": [ch], "hyp_txt": l}
    if tok in ("∨", "\\/", "∧", "/\\"):
        l, r = t[:idx].strip(), t[idx + len(tok):].strip()
        cl = build_tree(l, types, hyps, nat_mode, depth + 1)
        cr = build_tree(r, types, hyps, nat_mode, depth + 1)
        return {"kind": "or" if tok in ("∨", "\\/") else "and", "children": [cl, cr]}
    # Leaf: first try the B6 isolated sqrt reduction, then an ordinary relational leaf.
    leaf = parse_goal_ext_rel(t, vs, types, nat_mode)
    if leaf is None:
        return {"kind": "fail", "reason": "leaf_no_rel"}
    rec = _mk_rec("<goal>", types, types, hyps, leaf, nat_mode)
    sq = build_sqrt_node(rec)
    if sq is not None:
        return sq
    got, why = F.chain_of(rec)
    return {"kind": "leaf", "rec": rec, "got": got, "why": why}


def _hyp_add(txt, vs, types, nat_mode, nm):
    h = parse_goal_ext_rel(txt, set(vs), types, nat_mode)
    if h is None:
        return []
    h["name"] = nm
    return [h]


def _mk_rec(name, vars_ty, types, hyps, concl, nat_mode):
    return {"name": name, "vars": dict(vars_ty), "types": dict(types), "hyps": list(hyps),
            "concl": concl, "ok": True, "n_vars": len(vars_ty),
            "has_complex": any(t in S.CPLX_TYPES for t in types.values()),
            "nat_mode": nat_mode}


# ================================================================ §3 B6 sqrt reduction certificate
_REL_FLIP = {"=": "=", "≤": "≥", "<": ">", "≥": "≤", ">": "<"}


def _side_proof_raw(T, need, rec):
    """Deterministic side-condition proof **tactic body** (the caller decides whether to wrap it
    as a `(by ...)` term or a `try ...` tactic line)."""
    try:
        zero = sp.Integer(0)
        for h in rec["hyps"]:
            if h.get("neg"):
                continue
            if h["lhs"] == zero and h["rhs"] == T:
                if h["rel"] == "<" and need == "0<":
                    return "exact %s" % h["name"], "hyp_exact"
                if h["rel"] == "<" and need == "0≤":
                    return "linarith", "hyp_lt_le"
                if h["rel"] == "≤" and need == "0≤":
                    return "exact %s" % h["name"], "hyp_exact"
        # Bound against a positive / non-negative constant (0 < T / 0 ≤ T derived by linarith).
        for h in rec["hyps"]:
            if h.get("neg"):
                continue
            for side, other, rel in ((h["rhs"], h["lhs"], h["rel"]),
                                     (h["lhs"], h["rhs"], h["rel"])):
                if side != T or other.free_symbols or rel not in ("≤", "<"):
                    continue
                ov = sp.nsimplify(other)
                if not ov.is_rational:
                    continue
                if need == "0<" and ov > 0:
                    return "linarith", "hyp_bound_pos"
                if need == "0≤" and ov >= 0:
                    return "linarith", "hyp_bound_nonneg"
        if T.free_symbols == set() and sp.nsimplify(T).is_rational:
            if need == "0<" and sp.nsimplify(T) > 0:
                return "norm_num", "closed_pos"
            if need == "0≤" and sp.nsimplify(T) >= 0:
                return "norm_num", "closed_nonneg"
        # Non-negativity inherited through an equality hypothesis on the variable.
        for h in rec["hyps"]:
            if h.get("neg") or h["rel"] != "=":
                continue
            tgt = None
            if h["lhs"] == T:
                tgt = h["rhs"]
            elif h["rhs"] == T:
                tgt = h["lhs"]
            if tgt is not None and not tgt.free_symbols:
                continue
            if tgt is not None:
                p = S.pos_ok(tgt, [], strict=(need == "0<"))
                if p:
                    return "rw [%s]; positivity" % h["name"], "hyp_pos"
        return "positivity", "positivity"
    except Exception:                                                   # noqa: BLE001
        return "positivity", "positivity"


def _side_proof(T, need, rec):
    """rw-argument form: `(by <tactic>)` = the rendered **payload segment**."""
    raw, src = _side_proof_raw(T, need, rec)
    return "(by %s)" % raw, src


def build_sqrt_node(rec):
    """Isolated sqrt: <sqrt side> ⋈ b  (rel in =,≤,<) -> sqrt_red node; otherwise None."""
    c = rec["concl"]
    if c.get("neg") or c["rel"] not in ("=", "≤", "<", "≥", ">"):
        return None
    lhs, rhs, rel = c["lhs"], c["rhs"], c["rel"]
    # D-B8 (device defect, fixed): the sqrt must be **strictly isolated** -- lhs/rhs themselves
    #   are the sqrt atom. The first version used has_sq() (any sqrt present), which misclassified
    #   sums such as "√a+√b+√c ≤ 3/2" as an isolated sqrt and took X = args[0], so the reduction
    #   goal was misplaced (the judging module then rejected it -- fail-closed, but the
    #   structural-layer reading was inflated).
    ls = getattr(lhs, "func", None) is SQ
    rs = getattr(rhs, "func", None) is SQ
    if ls and rs:
        return None
    if ls:
        X, b, mirror, rel2 = lhs.args[0], rhs, False, rel
    elif rs:
        X, b, mirror, rel2 = rhs.args[0], lhs, True, _REL_FLIP[rel]
    else:
        return None
    if rel2 not in ("=", "≤", "<"):
        return None
    try:
        b2 = sp.expand(b ** 2)
    except Exception:                                                   # noqa: BLE001
        return None
    # Reduction goal.
    rl, rr = (b2, X) if (mirror and rel2 != "=") else (X, b2)
    if rel2 == "<":
        need_b = "0<"
    else:
        need_b = "0≤"
    hb, src_b = _side_proof(b, need_b, rec)
    if mirror and rel2 == "=":
        lead = ["try rw [eq_comm]"]
    else:
        lead = []
    if mirror and rel2 == "≤":
        hx, _sx = _side_proof(X, "0≤", rec)
        head = lead + ["try rw [Real.le_sqrt (%s) (%s)]" % (hb, hx)]
    elif mirror and rel2 == "<":
        head = lead + ["try rw [Real.lt_sqrt (%s)]" % hb]
    elif rel2 == "=":
        hx, _sx = _side_proof(X, "0≤", rec)
        head = lead + ["try rw [Real.sqrt_eq_iff_eq_sq (%s) (%s)]" % (hx, hb)]
    elif rel2 == "≤":
        raw, _src = _side_proof_raw(b, "0≤", rec)
        head = ["try rw [Real.sqrt_le_iff]", "try constructor", "try %s" % raw]
    else:                                                               # rel2 == "<"
        hx, _sx = _side_proof(X, "0≤", rec)
        head = ["try rw [Real.sqrt_lt (%s) (%s)]" % (hx, hb)]
    concl2 = {"rel": rel2, "neg": False, "lhs": rl, "rhs": rr,
              "meta": meta_of(rl - rr)}
    rec2 = dict(rec)
    rec2["concl"] = concl2
    got, why = F.chain_of(rec2)
    node = {"kind": "sqrt_red", "rec": rec, "rec2": rec2, "got": got, "why": why,
            "head": head, "mirror": mirror, "rel2": rel2, "X": X, "b": b,
            "side_b": src_b, "ops": ["g44_sqrt_iso", "g44_sqrt_sq", "g44_sqrt_close"]}
    return node


# ================================================================ §4 certifiability + rendering
def certifiable(node):
    k = node.get("kind")
    if k == "fail":
        return False
    if k == "leaf":
        return node.get("got") is not None
    if k == "sqrt_red":
        return node.get("got") is not None
    if k == "or":
        return any(certifiable(x) for x in node["children"])
    if k in ("and", "iff", "imp", "forall"):
        return all(certifiable(x) for x in node["children"])
    return False


